#!/usr/bin/env node
// Generate the OpenCode files that mirror this repo's sources:
//   .opencode/command/ and .opencode/commands/  one slash command per
//     user-invoked skill (OpenCode 1 reads command/, 2 prefers commands/);
//     the skill stays the single source, the command only points at it.
//   .opencode/agents/  one subagent per agents/*.md, with the Claude-style
//     tools: list turned into a deny-first permission map.
//
// Usage: gen-opencode.mjs [--check]   (--check exits 1 when files are stale)

import fs from 'node:fs';
import path from 'node:path';
import { ROOT, listSkills, listAgents, agentTools, userInvoked } from './lib/skills.mjs';
import { isMain } from '../skills/it-core/scripts/is-main.mjs';

const OUT = path.join(ROOT, '.opencode');

export function commandFor(skill) {
  const description = String(skill.meta.description || '').replace(/\s+/g, ' ').trim();
  return [
    '---',
    `description: ${JSON.stringify(description)}`,
    '---',
    '',
    '<!-- Generated by scripts/gen-opencode.mjs from skills/' + skill.dir + '/SKILL.md. Do not edit. -->',
    '',
    `Load the \`${skill.meta.name}\` skill with the skill tool and follow it exactly.`,
    '',
    'Arguments: $ARGUMENTS',
    '',
  ].join('\n');
}

// Model-invoked skills that also deserve a slash command.
const ALSO_COMMANDS = new Set(['log-it', 'guard-it', 'map-it', 'sweep-it', 'look-it-up', 'merge-it']);

export function expected() {
  return Object.fromEntries(
    listSkills()
      .filter((s) => userInvoked(s) || ALSO_COMMANDS.has(s.meta.name))
      .map((s) => [`${s.meta.name}.md`, commandFor(s)]),
  );
}

// Claude Code tool name -> OpenCode permission keys. Tools with no entry
// (Skill, WebFetch, ...) are not granted.
const PERMISSIONS = {
  Read: ['read'],
  Grep: ['grep'],
  Glob: ['glob', 'list'],
  Bash: ['bash'],
  Write: ['edit'],
  Edit: ['edit'],
  MultiEdit: ['edit'],
  NotebookEdit: ['edit'],
};

// Both OpenCode 1.18 and the dev snapshot apply the `permission` map and
// ignore a `permissions` list, which would leave the agent allow-all.
export function agentFor(agent) {
  const description = String(agent.meta.description || '').replace(/\s+/g, ' ').trim();
  const tools = agentTools(agent);
  const grants = [...new Set(tools.flatMap((t) => PERMISSIONS[t] ?? []))];
  const head = ['---', `description: ${JSON.stringify(description)}`, 'mode: subagent'];
  if (tools.length) head.push('permission:', '  "*": deny', ...grants.map((g) => `  ${g}: allow`));
  // Notes go below the frontmatter: the repo's own parser reads a YAML comment as part of the previous value.
  const notes = [];
  if (agent.meta.model) notes.push(`tier: ${agent.meta.model} (OpenCode has no tiers; set model in opencode.json if wanted)`);
  if (!tools.length) notes.push('tools: all (source lists none)');
  head.push('---', '', `<!-- Generated by scripts/gen-opencode.mjs from agents/${agent.name}.md. Do not edit. ${notes.join('; ')}. -->`, '');
  return `${head.join('\n')}\n${agent.body.replace(/^\s+/, '')}`;
}

export function expectedAgents() {
  return Object.fromEntries(listAgents().map((a) => [`${a.name}.md`, agentFor(a)]));
}

// Every generated directory and the files it must hold, exactly.
export function targets() {
  const commands = expected();
  return [
    { dir: path.join(OUT, 'command'), files: commands },
    { dir: path.join(OUT, 'commands'), files: commands },
    { dir: path.join(OUT, 'agents'), files: expectedAgents() },
  ];
}

function main() {
  const check = process.argv.includes('--check');
  const problems = [];
  let total = 0;

  for (const { dir, files } of targets()) {
    const have = fs.existsSync(dir) ? fs.readdirSync(dir).filter((f) => f.endsWith('.md')) : [];
    const stale = Object.entries(files)
      .filter(([file, text]) => !fs.existsSync(path.join(dir, file)) || fs.readFileSync(path.join(dir, file), 'utf8') !== text)
      .map(([file]) => file);
    const extra = have.filter((f) => !(f in files));
    total += Object.keys(files).length;
    if (check) {
      problems.push(...[...stale, ...extra].map((f) => `${path.basename(dir)}/${f}`));
      continue;
    }
    fs.mkdirSync(dir, { recursive: true });
    for (const file of stale) fs.writeFileSync(path.join(dir, file), files[file]);
    for (const file of extra) fs.rmSync(path.join(dir, file));
    console.log(`${path.basename(dir)}: wrote ${stale.length}, removed ${extra.length}, ${Object.keys(files).length} total.`);
  }

  if (check) {
    if (problems.length) {
      console.error(`OpenCode files out of date: ${problems.join(', ')}. Run: npm run gen`);
      process.exit(1);
    }
    console.log(`OpenCode files up to date (${total}).`);
  }
}

if (isMain(import.meta.url)) main();
