#!/usr/bin/env node
// Generate .opencode/command/<name>.md for every user-invoked skill, so
// /do-it, /scope-it and the rest work as slash commands in OpenCode. The
// skill stays the single source; the command only points at it.
//
// Usage: gen-opencode.mjs [--check]   (--check exits 1 when files are stale)

import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';
import { ROOT, listSkills, userInvoked } from './lib/skills.mjs';

const OUT = path.join(ROOT, '.opencode', 'command');

export function commandFor(skill) {
  const description = String(skill.meta.description || '').replace(/\s+/g, ' ').trim();
  return [
    '---',
    `description: ${JSON.stringify(description)}`,
    '---',
    '',
    '<!-- Generated by scripts/gen-opencode.mjs from skills/' + skill.dir + '/SKILL.md. Do not edit. -->',
    '',
    `Load the \`${skill.meta.name}\` skill with the skill tool and follow it exactly.`,
    '',
    'Arguments: $ARGUMENTS',
    '',
  ].join('\n');
}

// Model-invoked skills that also deserve a slash command.
const ALSO_COMMANDS = new Set(['log-it', 'guard-it', 'map-it', 'sweep-it', 'look-it-up', 'merge-it', 'todo-it']);

export function expected() {
  return Object.fromEntries(
    listSkills()
      .filter((s) => userInvoked(s) || ALSO_COMMANDS.has(s.meta.name))
      .map((s) => [`${s.meta.name}.md`, commandFor(s)]),
  );
}

function main() {
  const check = process.argv.includes('--check');
  const want = expected();
  const have = fs.existsSync(OUT) ? fs.readdirSync(OUT).filter((f) => f.endsWith('.md')) : [];
  const stale = [];

  for (const [file, text] of Object.entries(want)) {
    const p = path.join(OUT, file);
    if (!fs.existsSync(p) || fs.readFileSync(p, 'utf8') !== text) stale.push(file);
  }
  const extra = have.filter((f) => !(f in want));

  if (check) {
    if (stale.length || extra.length) {
      console.error(`OpenCode commands out of date: ${[...stale, ...extra].join(', ')}. Run: npm run gen`);
      process.exit(1);
    }
    console.log(`OpenCode commands up to date (${Object.keys(want).length}).`);
    return;
  }

  fs.mkdirSync(OUT, { recursive: true });
  for (const file of stale) fs.writeFileSync(path.join(OUT, file), want[file]);
  for (const file of extra) fs.rmSync(path.join(OUT, file));
  console.log(`Wrote ${stale.length}, removed ${extra.length}, ${Object.keys(want).length} total.`);
}

function isMain() {
  try {
    return Boolean(process.argv[1]) && fs.realpathSync(process.argv[1]) === fs.realpathSync(fileURLToPath(import.meta.url));
  } catch {
    return false;
  }
}

if (isMain()) main();
